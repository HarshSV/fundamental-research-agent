"""Sector outlook: odds for the next 1 and 3 months from how each sector behaved after similar situations, with the current facts beside them.

The odds
  * A sector's "situation" in a month is three yes/no facts known at that month's end: did it rise over the last 3 months, did it beat all
    stocks over the last 6 months, is it more than 15% below its own peak.
  * The odds are the shares of past months in the same situation that were followed by a clear rise, a flat stretch or a clear fall
    ("clear" = more than a quarter of the typical swing, as in the stock forecast). With fewer than 30 such months for the sector, the same
    situation across all sectors is used; with fewer than 30 of those, all of the sector's months.
  * `validation()` replays that method month by month using only what was known then, and reports how often its calls were right next to the
    plain rate of rising months. The page shows it, so the odds are read with their record.

The facts (not blended into the odds, shown beside them): trend and strength against all stocks, the share of its stocks above their 50 and
200-day averages, results reported this quarter and their growth, order and deal flow, results due soon, the sector's usual tendency in the
coming calendar months, and what it has done in market rises and falls.

Nothing is generated by a model. A figure that cannot be computed is None."""
from __future__ import annotations

import statistics
from datetime import date, datetime, timedelta

import numpy as np

from . import exchange_data as ex
from . import market_analytics, scan, sector_events, sector_history, upcoming

MIN_STATE = 30
HORIZONS = (("1m", 1), ("3m", 3))
STRONG, MODERATE, EVEN = 0.25, 0.12, 0.03          # same thresholds as the stock forecast (setups/outlook.py)
DD_LINE = -0.15
_cache: dict = {}
_val_cache: dict = {}


def _label(i: int) -> str:
    return f"{i // 12}-{i % 12 + 1:02d}"


def lean(up: float, down: float) -> dict:
    gap = abs(up - down)
    if gap < EVEN:
        return {"call": "even", "conviction": None}
    return {"call": "up" if up > down else "down", "conviction": "strong" if gap >= STRONG else "moderate" if gap >= MODERATE else "slight"}


def _state(L: dict, M: dict, t: int):
    """(rose over 3 months, beat the market over 6 months, far below its peak) at month t, or None when it cannot be known."""
    if t - 6 not in L or t - 6 not in M or t not in M:
        return None
    peak = max(v for i, v in L.items() if i <= t)
    r3 = L[t] / L[t - 3] - 1.0 if t - 3 in L else None
    if r3 is None:
        return None
    rel6 = (L[t] / L[t - 6]) - (M[t] / M[t - 6])
    return (r3 > 0, rel6 > 0, L[t] / peak - 1.0 < DD_LINE)


def _samples(sector: str, L: dict, M: dict):
    """Per month t: (t, state, {h: (forward return, forward excess over the market)}) for months whose state is known."""
    out = []
    for t in sorted(L):
        st = _state(L, M, t)
        if st is None:
            continue
        fw = {}
        for _, h in HORIZONS:
            if t + h in L and t + h in M and t in M:
                fw[h] = (L[t + h] / L[t] - 1.0, (L[t + h] / L[t]) - (M[t + h] / M[t]))
        out.append((t, st, fw))
    return out


def _tilt(points: float) -> dict:
    """What the situation adds to the sector's usual odds, in percentage points of the chance of a clear rise."""
    a = abs(points)
    return {"direction": "none" if a < 5 else "up" if points > 0 else "down", "size": "none" if a < 5 else "clear" if a >= 10 else "slight"}


def _odds(pool: list[tuple[float, float]], band: float, base: list[tuple[float, float]] | None = None) -> dict:
    rets = np.array([p[0] for p in pool])
    exc = np.array([p[1] for p in pool])
    up, down = float((rets > band).mean()), float((rets < -band).mean())
    extra = {}
    if base:
        br, bx = np.array([p[0] for p in base]), np.array([p[1] for p in base])
        b_up, b_down, b_beat = float((br > band).mean()), float((br < -band).mean()), float((bx > 0).mean())
        extra = {"usual_up": round(b_up * 100), "usual_down": round(b_down * 100), "usual_beat_market": round(b_beat * 100),
                 "tilt_up_points": round((up - b_up) * 100), "tilt_beat_points": round((float((exc > 0).mean()) - b_beat) * 100),
                 "tilt": _tilt((up - b_up) * 100)}
    return {**lean(up, down), **extra, "up": round(up * 100), "flat": round((1 - up - down) * 100), "down": round(down * 100),
            "beat_market": round(float((exc > 0).mean()) * 100), "p10": round(float(np.percentile(rets, 10)) * 100, 1),
            "median": round(float(np.percentile(rets, 50)) * 100, 1), "p90": round(float(np.percentile(rets, 90)) * 100, 1),
            "samples": len(pool), "flat_band_pct": round(band * 100, 2)}


def _describe(st) -> str:
    a, b, c = st
    return ", ".join([("rose over the last 3 months" if a else "fell over the last 3 months"),
                      ("beat all stocks over 6 months" if b else "trailed all stocks over 6 months"),
                      ("more than 15% below its own peak" if c else "within 15% of its own peak")])


def _estimate(h: int, state, own: list, pooled: list, own_all: list) -> dict:
    """Odds for horizon h from the sector's own months in this state, else all sectors' months in it, else all of the sector's months."""
    band = 0.25 * statistics.pstdev([x[0] for x in own_all]) if len(own_all) > 2 else 0.0
    if len(own) >= MIN_STATE:
        return {**_odds(own, band, own_all), "basis": "this sector, same situation"}
    if len(pooled) >= MIN_STATE:
        return {**_odds(pooled, band, own_all), "basis": "all sectors, same situation"}
    if len(own_all) >= MIN_STATE:
        return {**_odds(own_all, band, own_all), "basis": "all of this sector's months"}
    return {"call": None, "reason": "Too little history to measure."}


def _collect():
    lv = sector_history.levels()
    if lv is None:
        return None
    M = lv["market"]
    data = {sec: _samples(sec, L, M) for sec, L in lv["sectors"].items()}
    return lv, data


def validation() -> dict:
    """Replay the method month by month on the past, using only what was known at each month. For months where the situation tilted the
    odds up (or down) by at least 10 points, how often did the sector rise (or beat all stocks) afterwards, against how often it did so
    in every tested month? A tilt that predicts something shows a clear gap; one that does not shows none."""
    got = _collect()
    if got is None:
        return {"ready": False}
    key = sector_history.os.path.getmtime(sector_history.STORE)
    if key in _val_cache:
        return _val_cache[key]
    _, data = got
    res = {}
    for _, h in HORIZONS:
        events = []                                  # (month the outcome is known, sector, state, forward return, excess)
        rows_by_t: dict = {}
        for sec, rows in data.items():
            for t, st, fw in rows:
                rows_by_t.setdefault(t, []).append((sec, st, fw))
                if h in fw:
                    events.append((t + h, sec, st, fw[h][0], fw[h][1]))
        events.sort(key=lambda e: e[0])
        by_state: dict = {}
        by_sec_state: dict = {}
        by_sec: dict = {}
        ptr = 0
        tested = []                                  # (tilt in points, rose, beat the market, tilt for beating, )
        for t in sorted(rows_by_t):
            while ptr < len(events) and events[ptr][0] <= t:     # only outcomes already known at month t
                _, sec, st, f, x = events[ptr]
                by_state.setdefault(st, []).append((f, x))
                by_sec_state.setdefault((sec, st), []).append((f, x))
                by_sec.setdefault(sec, []).append((f, x))
                ptr += 1
            for sec, st, fw in rows_by_t[t]:
                if h not in fw or len(by_sec.get(sec, [])) < MIN_STATE:
                    continue
                o = _estimate(h, st, by_sec_state.get((sec, st), []), by_state.get(st, []), by_sec[sec])
                if o.get("tilt_up_points") is None:
                    continue
                tested.append((o["tilt_up_points"], fw[h][0] > 0, fw[h][1] > 0, o["tilt_beat_points"]))
        n = len(tested)
        rose = sum(1 for x in tested if x[1]) / n * 100 if n else None
        beat = sum(1 for x in tested if x[2]) / n * 100 if n else None

        def grp(pred, idx):
            g = [x for x in tested if pred(x)]
            return {"months": len(g), "share": round(sum(1 for x in g if x[idx]) / len(g) * 100, 1) if len(g) >= 30 else None}
        res[f"{h}m"] = {"months_tested": n, "usual_rose": round(rose, 1) if rose is not None else None,
                        "usual_beat_market": round(beat, 1) if beat is not None else None,
                        "tilt_up_rose": grp(lambda x: x[0] >= 10, 1), "tilt_down_rose": grp(lambda x: x[0] <= -10, 1),
                        "tilt_up_beat": grp(lambda x: x[3] >= 10, 2), "tilt_down_beat": grp(lambda x: x[3] <= -10, 2)}
    out = {"ready": True, "horizons": res,
           "meaning": "Months are counted only when the odds could be worked out from earlier months alone. 'Usual' is the share of all tested months that rose "
                      "or beat all stocks; it is high because the stocks tested are today's survivors. A tilt only matters if the months it flagged did "
                      "noticeably better (or worse) than that."}
    _val_cache.clear()
    _val_cache[key] = out
    return out


# ------------------------------------------------------------------ current facts
def _results_progress(syms: set) -> dict:
    from screens import quarterly as qt
    data = qt.load()
    latest = qt.latest_quarter(data) if data else None
    if not latest:
        return {"available": False}
    rep, sales, np_ = 0, [], []
    for s in syms:
        d = qt.derive(data.get(s), latest)
        if d.get("f_latest_quarter"):
            rep += 1
            if d.get("sales_yoy") is not None:
                sales.append(d["sales_yoy"])
            if d.get("np_yoy") is not None:
                np_.append(d["np_yoy"])
    return {"available": True, "quarter": latest, "reported": rep, "of": len(syms),
            "median_sales_yoy": round(statistics.median(sales), 1) if len(sales) >= 3 else None,
            "median_profit_yoy": round(statistics.median(np_), 1) if len(np_) >= 3 else None,
            "profit_up_share": round(sum(1 for x in np_ if x > 0) / len(np_) * 100) if len(np_) >= 3 else None}


def _drivers(sector: str, L: dict, M: dict, t: int, rows: dict, row_stats: dict | None) -> list[dict]:
    d = []
    for lab, n in (("3 months", 3), ("6 months", 6), ("12 months", 12)):
        if t - n in L and t - n in M:
            s, m = L[t] / L[t - n] - 1, M[t] / M[t - n] - 1
            d.append({"label": f"Last {lab}", "value": f"{s * 100:+.1f}% (all stocks {m * 100:+.1f}%)", "tone": "up" if s > m else "down",
                      "detail": "ahead of the market" if s > m else "behind the market"})
    peak = max(v for i, v in L.items() if i <= t)
    d.append({"label": "Versus its own peak", "value": f"{(L[t] / peak - 1) * 100:+.1f}%", "tone": "up" if L[t] / peak - 1 > DD_LINE else "down"})
    if row_stats:
        if row_stats.get("above_50") is not None:
            d.append({"label": "Stocks above their 50-day average", "value": f"{row_stats['above_50']:.0f}%", "tone": "up" if row_stats["above_50"] >= 50 else "down"})
        if row_stats.get("above_200") is not None:
            d.append({"label": "Stocks above their 200-day average", "value": f"{row_stats['above_200']:.0f}%", "tone": "up" if row_stats["above_200"] >= 50 else "down"})
        if row_stats.get("quadrant"):
            d.append({"label": "Rotation quadrant", "value": row_stats["quadrant"].capitalize(), "tone": "up" if row_stats["quadrant"] in ("leading", "improving") else "down"})
    return d


def _seasonal_next(sector: str, built: dict | None, months_ahead: int = 3) -> list[dict]:
    if not built:
        return []
    sec = next((s for s in built.get("sectors", []) if s["sector"] == sector and s.get("available")), None)
    if not sec:
        return []
    today = date.today()
    out = []
    for k in range(1, months_ahead + 1):
        m = (today.month - 1 + k) % 12 + 1
        sm = next((x for x in sec["seasonal"] if x["month"] == m), None)
        if sm and sm["average"] is not None:
            out.append({"month": m, "average": sm["average"], "positive_share": sm["positive_share"], "years": sm["months"]})
    return out


def sector(name: str) -> dict:
    return next((s for s in outlook()["sectors"] if s["sector"] == name), {"sector": name, "available": False})


def outlook() -> dict:
    got = _collect()
    if got is None:
        return {"ready": False, "note": "The sector history has not been built yet.", "sectors": []}
    lv, data = got
    M = lv["market"]
    key = ("out", sector_history.os.path.getmtime(sector_history.STORE), date.today().isoformat())
    if key in _cache:
        return _cache[key]
    try:
        live = {r["name"]: r for r in market_analytics.sectors().get("sectors", [])}
    except Exception:
        live = {}
    built = sector_history.build("full")
    rows = scan._load_all()
    pooled: dict = {h: {} for _, h in HORIZONS}
    for sec, rs in data.items():
        for t, st, fw in rs:
            for h, v in fw.items():
                pooled[h].setdefault(st, []).append(v)
    cal = ex.load("calendar") or []
    horizon = (date.today() + timedelta(days=21)).isoformat()
    out = []
    for sec, L in lv["sectors"].items():
        t = max(L)
        st = _state(L, M, t)
        if st is None:
            continue
        syms = {s for s, r in rows.items() if r.get("sector") == sec}
        own = {h: [v for tt, s2, fw in data[sec] if s2 == st and h in fw for v in [fw[h]]] for _, h in HORIZONS}
        own_all = {h: [fw[h] for _, _, fw in data[sec] if h in fw] for _, h in HORIZONS}
        hz = []
        for hid, h in HORIZONS:
            hz.append({"id": hid, **_estimate(h, st, own[h], pooled[h].get(st, []), own_all[h])})
        ev = sector_events.analyse(sec)
        scen = None
        if ev.get("available") and ev.get("up_capture") is not None and ev.get("down_capture") is not None:
            scen = {"market_down_10": round(-10 * ev["down_capture"] / 100, 1), "market_up_10": round(10 * ev["up_capture"] / 100, 1),
                    "beta": ev.get("beta")}
        res = _results_progress(syms)
        rc = sector_events.recent(sec)
        up_res = sum(1 for c in cal if c.get("symbol") in syms and date.today().isoformat() <= (c.get("date") or "") <= horizon)
        drivers = _drivers(sec, L, M, t, rows, live.get(sec))
        out.append({"sector": sec, "available": True, "as_of": _label(t), "stocks": len(syms), "situation": _describe(st), "horizons": hz,
                    "drivers": drivers, "scenarios": scen, "results": res,
                    "flow": {"orders_2w": rc.get("orders_count"), "deals_buy_cr": rc.get("deals_buy_cr"), "deals_sell_cr": rc.get("deals_sell_cr"),
                             "deals_count": rc.get("deals_count")},
                    "upcoming": {"results_due_21d": up_res, "seasonal_next_3": _seasonal_next(sec, built), "actions": upcoming.sector_actions(sec)}})
    out.sort(key=lambda x: -(x["horizons"][1].get("tilt_up_points") if x["horizons"][1].get("tilt_up_points") is not None else -999))
    res = {"ready": True, "as_of": _label(max(max(L) for L in lv["sectors"].values())), "sectors": out, "validation": validation(), "scheduled": upcoming.market(90),
           "note": "Odds are how this sector behaved after similar situations, not a prediction. The facts beside them are not blended into the odds."}
    _cache.clear()
    _cache[key] = res
    return res
